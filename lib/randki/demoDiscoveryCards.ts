import type { RandkiDiscoveryCard } from "@/lib/randki/matching";
import { demoRoomPhasesJson, DEMO_PERSONA_META } from "@/lib/randki/demoRoomProfiles";

export const DEMO_DISCOVERY_PREFIX = "demo-room-";

export function isDemoDiscoveryAccountId(accountId: string): boolean {
  return accountId.startsWith(DEMO_DISCOVERY_PREFIX);
}

export function shouldShowDemoDiscoveryRooms(): boolean {
  return process.env.RANDKI_DEMO_ROOMS === "1" || process.env.RANDKI_DEMO_ROOMS === "true";
}

const U = (id: string, w = 600) => `https://images.unsplash.com/photo-${id}?w=${w}&q=80`;
const P = (id: string) => U(id, 480);
const A = (id: string) => U(id, 720);

function card(
  n: number,
  data: Omit<
    RandkiDiscoveryCard,
    | "accountId"
    | "compatibilityScore"
    | "interestScore"
    | "socialProof"
    | "intention"
    | "communicationStyle"
    | "circleSlug"
    | "recentlyActive"
    | "roomPhasesJson"
    | "voiceIntroUrl"
    | "activityIntent"
  > & { activityIntent?: string | null; voiceIntroUrl?: string | null }
): RandkiDiscoveryCard {
  const id = `${DEMO_DISCOVERY_PREFIX}${String(n).padStart(2, "0")}`;
  const persona = DEMO_PERSONA_META[n];
  return {
    accountId: id,
    compatibilityScore: 72 + (n % 23),
    interestScore: 2 + (n % 4),
    socialProof: ["odpowiada wieczorem", "świeży moment dziś", "pokój ustawiony na wszystkie pory"],
    intention: "relacja",
    communicationStyle: "spokojnie",
    circleSlug: null,
    recentlyActive: true,
    roomPhasesJson: demoRoomPhasesJson(n),
    ...data,
    activityIntent: data.activityIntent ?? (n % 2 === 0 ? "walk" : "coffee"),
    voiceIntroUrl: data.voiceIntroUrl ?? (persona?.hasVoice ? `/randki/demo/voice-${String(n).padStart(2, "0")}.wav` : null),
  };
}

